/**
 * components/SwipeRow.tsx
 * Swipe-to-reveal row (restyled after React Bits SwipeRow): transparent, radius 0, no shadows,
 * no border on the container, tokens only.
 * - Swipe left (touch/pen/mouse drag) reveals "Arsip" and "Hapus".
 * - Non-gesture alternative: long press (500ms) opens the actions, and a 44px "Aksi" button
 *   appears on keyboard focus (and on hover for mouse users).
 * - The first row nudges once to hint the gesture; the hint flag is stored in localStorage.
 */
"use client";

import { useRef, useState, useCallback, useEffect } from "react";

interface SwipeRowProps {
  children: React.ReactNode;
  onArchive?: () => void;
  onDelete?: () => void;
  ariaLabel?: string;
  isFirst?: boolean;
}

const ACTION_W = 80;
const THRESHOLD = 40;
const LONG_PRESS_MS = 500;
const NUDGE_KEY = "rn_swipe_nudge_shown";
const HINT_KEY = "rn_swipe_hint_shown";

function markHintDone() {
  try {
    if (localStorage.getItem(HINT_KEY) !== "true") {
      localStorage.setItem(HINT_KEY, "true");
      window.dispatchEvent(new Event("rn_swipe_hint"));
    }
  } catch {
    /* storage unavailable: ignore */
  }
}

export function SwipeRow({ children, onArchive, onDelete, ariaLabel = "Baris tugas", isFirst = false }: SwipeRowProps) {
  const [offset, setOffset] = useState(0);
  const [open, setOpen] = useState(false);
  const [dragging, setDragging] = useState(false);
  const startX = useRef<number | null>(null);
  const startY = useRef(0);
  const moved = useRef(false);
  const suppressClick = useRef(false);
  const longPressTimer = useRef<ReturnType<typeof setTimeout> | null>(null);

  const maxOffset = -(ACTION_W * 2);

  const setOpenState = useCallback(
    (next: boolean) => {
      setOpen(next);
      setOffset(next ? maxOffset : 0);
      if (next) markHintDone();
    },
    [maxOffset]
  );

  // One-time gesture nudge on the first row (skipped under reduced motion).
  useEffect(() => {
    if (!isFirst) return;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    if (localStorage.getItem(NUDGE_KEY)) return;
    localStorage.setItem(NUDGE_KEY, "true");
    const t1 = setTimeout(() => setOffset(-44), 700);
    const t2 = setTimeout(() => setOffset(0), 1300);
    return () => {
      clearTimeout(t1);
      clearTimeout(t2);
    };
  }, [isFirst]);

  const clearLongPress = () => {
    if (longPressTimer.current) clearTimeout(longPressTimer.current);
    longPressTimer.current = null;
  };

  const onPointerDown = (e: React.PointerEvent) => {
    if (e.pointerType === "mouse" && e.button !== 0) return;
    startX.current = e.clientX;
    startY.current = e.clientY;
    moved.current = false;
    suppressClick.current = false;
    clearLongPress();
    longPressTimer.current = setTimeout(() => {
      suppressClick.current = true;
      startX.current = null;
      setOpenState(!open);
    }, LONG_PRESS_MS);
  };

  const onPointerMove = (e: React.PointerEvent) => {
    if (startX.current === null) return;
    const dx = e.clientX - startX.current;
    const dy = e.clientY - startY.current;
    if (!moved.current) {
      if (Math.abs(dy) > 10 && Math.abs(dy) > Math.abs(dx)) {
        // Vertical scroll: give up on the swipe.
        clearLongPress();
        startX.current = null;
        return;
      }
      if (Math.abs(dx) < 6) return;
      moved.current = true;
      clearLongPress();
      setDragging(true);
      (e.currentTarget as Element).setPointerCapture?.(e.pointerId);
    }
    const base = open ? maxOffset : 0;
    setOffset(Math.max(maxOffset, Math.min(0, base + dx)));
  };

  const onPointerUp = () => {
    clearLongPress();
    if (startX.current !== null && moved.current) {
      suppressClick.current = true;
      setOpenState(offset < -THRESHOLD);
    }
    startX.current = null;
    setDragging(false);
  };

  // Block the link click that follows a swipe / long press; a tap on an open row closes it.
  const onClickCapture = (e: React.MouseEvent) => {
    if (suppressClick.current) {
      // Click generated by the swipe / long press itself: swallow it, keep the row state.
      e.preventDefault();
      e.stopPropagation();
      suppressClick.current = false;
      return;
    }
    if (open && !(e.target as Element).closest(".rn-swipe-aksi")) {
      e.preventDefault();
      e.stopPropagation();
      setOpenState(false);
    }
  };

  const onKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === "Escape" && open) setOpenState(false);
  };

  return (
    <div className="rn-swipe" role="group" aria-label={ariaLabel} onKeyDown={onKeyDown}>
      {/* Foreground row */}
      <div
        className="rn-swipe-front"
        onPointerDown={onPointerDown}
        onPointerMove={onPointerMove}
        onPointerUp={onPointerUp}
        onPointerCancel={onPointerUp}
        onClickCapture={onClickCapture}
        onDragStart={(e) => e.preventDefault()}
        onContextMenu={(e) => {
          if (longPressTimer.current || suppressClick.current) e.preventDefault();
        }}
        style={{
          transform: `translateX(${offset}px)`,
          transition: dragging ? "none" : "transform 250ms ease-out",
        }}
      >
        {children}
        <button
          type="button"
          className="rn-btn rn-btn-secondary rn-swipe-aksi"
          data-variant="secondary"
          onClick={() => setOpenState(!open)}
          aria-expanded={open}
          aria-label={open ? "Tutup aksi tugas" : "Buka aksi tugas"}
        >
          Aksi
        </button>
      </div>

      {/* Actions behind the row (after it in DOM so Tab goes row -> Aksi -> Arsip -> Hapus) */}
      <div
        className="rn-swipe-actions"
        aria-hidden={!open}
        data-visible={open || offset !== 0}
        style={{ width: Math.abs(offset), transition: dragging ? "none" : "width 250ms ease-out" }}
      >
        <button
          type="button"
          tabIndex={open ? 0 : -1}
          onClick={() => {
            setOpenState(false);
            onArchive?.();
          }}
          className="rn-swipe-action"
          style={{ background: "var(--rn-accent)" }}
          aria-label="Arsipkan tugas"
        >
          Arsip
        </button>
        <button
          type="button"
          tabIndex={open ? 0 : -1}
          onClick={() => {
            setOpenState(false);
            onDelete?.();
          }}
          className="rn-swipe-action"
          style={{ background: "var(--rn-alert)" }}
          aria-label="Hapus tugas"
        >
          Hapus
        </button>
      </div>
    </div>
  );
}
